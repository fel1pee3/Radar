"""Operator confirmation preserves existing config/queue and does not touch capture."""

import json
from pathlib import Path

import pytest
import yaml
from test_posture_multiclass import classifier

from radar_edge.errors import EdgeError
from radar_edge.posture_context import confirm_context


@pytest.mark.parametrize(
    "method,version",
    [
        ("MULTICLASS_BODY_V3", "floor-rtmo-score-posture-multiclass-v3-synthetic"),
        ("MULTICLASS_CONTEXT_V4", "floor-rtmo-score-posture-context-v4-synthetic"),
    ],
)
def test_context_confirmation_requires_action_and_preserves_old_queue(
    tmp_path, monkeypatch, method, version
):
    from radar_edge import posture_context

    model, cal, _ = classifier(tmp_path, monkeypatch, 3)
    # Reuse the actual validated synthetic config generated by the contract helper.
    from temporal_support import config

    c = config()
    c.model.variant = "rtmo-s"
    c.model.path = ".local/not-opened.onnx"
    c.posture = model.settings
    c.posture.method = method
    c.events.policy = {
        "version": version,
        "qualitySource": "RTMO_KEYPOINT_SCORE",
        "temporalMode": "EVIDENCE_V2",
    }
    c.calibrationPath = ".local/calibration.json"
    cal = {**cal, "schemaVersion": 1, "operatorConfirmed": True, "cameraId": c.cameraId}
    Path(c.calibrationPath).write_text(json.dumps(cal))
    path = Path(".local/config.yaml")
    path.write_text(yaml.safe_dump(c.model_dump()))
    queue = Path(c.events.outboxPath)
    queue.write_bytes(b"preserved synthetic queue, not opened")
    monkeypatch.setattr(posture_context, "verify_model", lambda *_: None)
    before = path.read_bytes()
    with pytest.raises(EdgeError, match="piso"):
        confirm_context(path)
    assert path.read_bytes() == before
    result = confirm_context(path, confirmed=True)
    assert Path(result["previousConfiguration"]).read_bytes() == before
    assert queue.read_bytes() == b"preserved synthetic queue, not opened"
    assert result["sourceOpened"] is False and result["outbox"] != str(queue)
